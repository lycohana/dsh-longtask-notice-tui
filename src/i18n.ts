export type NoticeTextKey = keyof typeof COPY.zh;

export function noticeText(lang: NoticeLanguage, key: NoticeTextKey, params: Record<string, string | number> = {}): string {
  const template = COPY[lang][key];
  return template.replace(/\{\{(\w+)\}\}/g, (_match, name: string) => String(params[name] ?? ""));
}
